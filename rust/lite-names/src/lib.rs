//! legend-lite's model index and name resolution, ported from core's `com.legend.compiler` root package (pipeline step
//! D; the first part of the compiler's split, `compiler/names` of rust/lite-guards/crate-layers.txt:
//! docs/rust-port/PHASE3_CRATES.md §2; docs/rust-port/PHASE3.md, the names slice, 2026-11-12).
//!
//! - [`resolver`]: `NameResolver` -- a model's names (strict, tolerant, alongside the boot layer's) and a query's (the
//!   sectionless scope, or a section's imports over a compiled model's universe), line for line, Java's answers,
//!   refusals and rebuilds included.
//! - [`model_index`]: `ModelBuilder` (the one index of a graph, with `SymbolTable` and `TableIndex`) and the store
//!   lookups; [`knowledge`]: `KnowledgeLayer`, its part that is step D's (the kernel E and F ask, the association
//!   adoption pass).
//! - [`bare_names`], [`resolved_names`], [`core_imports`] (generated by `//spec:gen_imports_rs`), [`synth_fqn`],
//!   [`derived_props`], [`relational_kinds`]: the rules the resolver and the later phases share.
//!
//! What the root package holds that waits for a later slice (it reaches F or G, PHASE3_CRATES.md §2's edges):
//! `StatementInline` (G's `Calls` and `SourceSubst`, F's `ModelContext`), `LiteralMapUnroll` (G's `SourceSubst`),
//! `KnowledgeLayer.columnKind` (F's `RelationalTypeInference`), and the query front door `Compiler.resolveQuery`,
//! which runs those passes after this crate's resolution.

