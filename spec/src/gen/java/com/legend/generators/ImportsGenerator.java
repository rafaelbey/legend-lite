package com.legend.generators;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * GENERATES {@code com/legend/compiler/CoreImports.java} whole: the engine's {@code CompileContext.META_IMPORTS},
 * in the engine's order (first-match resolution makes order semantic — see {@link CoreImportsParityTest}). It reads
 * CompileContext.java alone, so only an upgrade moves it.
 *
 * <pre>
 *   ImportsGenerator &lt;CompileContext.java&gt; &lt;output&gt; [--rust]
 * </pre>
 *
 * A build action (spec/BUILD.bazel, :gen_imports); the committed file is kept equal
 * to its output by //core:update_generated and its diff test. With {@code --rust}
 * (2026-11-12, docs/rust-port/PHASE3.md, the names slice) it writes the same sequence
 * for the Rust port, {@code rust/lite-names/src/core_imports.rs} (:gen_imports_rs, held
 * by //rust/lite-names:update_generated's diff test), from the same input.
 */
public final class ImportsGenerator {

    private ImportsGenerator() {}

    public static void main(String[] args) throws IOException {
        boolean rust = args.length == 3 && args[2].equals("--rust");
        if (args.length != 2 && !rust) {
            throw new IllegalArgumentException("usage: ImportsGenerator <CompileContext.java> <output> [--rust]");
        }
        List<String> imports = metaImports(Files.readString(Path.of(args[0]), StandardCharsets.UTF_8));
        Files.writeString(Path.of(args[1]), rust ? renderRust(imports) : render(imports), StandardCharsets.UTF_8);
        System.out.println("[imports] generated " + imports.size() + " packages" + (rust ? " (Rust)" : ""));
    }

    /** rust/lite-names/src/core_imports.rs's text for {@code imports}: the same sequence as {@link #render}'s, in the
     *  same order, as a Rust constant; LF on every platform. */
    public static String renderRust(List<String> imports) {
        if (imports.isEmpty()) {
            throw new IllegalStateException("CompileContext.META_IMPORTS named no package — upstream moved it");
        }
        StringBuilder out = new StringBuilder();
        out.append("// GENERATED by //spec:gen_imports_rs (spec/src/gen/java/com/legend/generators/ImportsGenerator.java, its\n")
                .append("// --rust form) from legend-engine's CompileContext.META_IMPORTS -- do not edit; regenerate with\n")
                .append("// `bazel run //rust/lite-names:update_generated` (and //:update_generated for the Java beside it,\n")
                .append("// core/src/main/java/com/legend/compiler/CoreImports.java).\n")
                .append("\n")
                .append("//! The implicit import group every element resolves through, walked FIRST-MATCH: the engine's sequence\n")
                .append("//! (`CompileContext.META_IMPORTS`: legend-pure's `system::imports::coreImport` plus the packages the engine\n")
                .append("//! adds, at the engine's positions). The order is semantic; Java's `CoreImportsParityTest` holds it.\n")
                .append("\n")
                .append("/// The packages, in the engine's order (Java's `CoreImports.SEQUENCE`).\n")
                .append("pub const SEQUENCE: &[&str] = &[\n");
        for (String pkg : imports) {
            out.append("    \"").append(pkg).append("\",\n");
        }
        return out.append("];\n").toString();
    }

    /** {@code META_IMPORTS}' packages, in order, from CompileContext.java's text. */
    public static List<String> metaImports(String compileContextJava) {
        int at = compileContextJava.indexOf("META_IMPORTS");
        if (at < 0) {
            throw new IllegalStateException("CompileContext.META_IMPORTS not found — upstream moved it");
        }
        int end = compileContextJava.indexOf(");", at);
        Matcher m = Pattern.compile("\"(meta::[A-Za-z0-9_:]+)\"").matcher(compileContextJava.substring(at, end));
        List<String> out = new ArrayList<>();
        while (m.find()) {
            out.add(m.group(1));
        }
        return out;
    }

    /** CoreImports.java's text for {@code imports}, LF on every platform. */
    public static String render(List<String> imports) {
        if (imports.isEmpty()) {
            throw new IllegalStateException("CompileContext.META_IMPORTS named no package — upstream moved it");
        }
        StringBuilder out = new StringBuilder();
        out.append("// GENERATED by //spec:gen_imports from legend-engine's CompileContext.META_IMPORTS -- do not edit.\n")
                .append("// Regenerate: bazel run //:update_generated\n")
                .append("package com.legend.compiler;\n\n")
                .append("import java.util.List;\n\n")
                .append("/**\n")
                .append(" * The implicit import group every element resolves through, walked FIRST-MATCH: the engine's\n")
                .append(" * sequence ({@code CompileContext.META_IMPORTS}: legend-pure's {@code system::imports::coreImport}\n")
                .append(" * plus the packages the engine adds, at the engine's positions). The order is semantic;\n")
                .append(" * {@code CoreImportsParityTest} holds it.\n")
                .append(" */\n")
                .append("public final class CoreImports {\n\n")
                .append("    private CoreImports() {}\n\n")
                .append("    /** The packages, in the engine's order. */\n")
                .append("    public static final List<String> SEQUENCE = List.of(\n");
        for (int k = 0; k < imports.size(); k++) {
            out.append("            \"").append(imports.get(k)).append('"').append(k + 1 < imports.size() ? ",\n" : ");\n");
        }
        return out.append("}\n").toString();
    }
}
